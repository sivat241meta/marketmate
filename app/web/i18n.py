def _fmt_number(value: Any) -> str:
    if value is None or value == "":
        return ""
    try:
        from decimal import Decimal

        return format(Decimal(str(value)).normalize(), "f")
    except (ArithmeticError, ValueError, AttributeError):
        return str(value)


