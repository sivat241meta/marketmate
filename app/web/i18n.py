STRINGS: dict[str, dict[str, str]] = {
    "en": _ENGLISH,
    "ta": _TAMIL,
    "hi": _HINDI,
}

_UI_LANGS = ("en", "ta", "hi")


def _normalize_lang(lang: str | None) -> str:
    text = (lang or "").strip().lower()
    return text if text in _UI_LANGS else "en"


class StringsDict(dict):
    """Customer ``t`` dict that is also callable as ``t(key, **vars)``.

    Customer templates use ``t.key`` lookups while the shared base layout
    calls ``t('top.…')``; both work in the customer's ``?lang`` language.
    Seller pages use the Jinja global ``t`` function instead.
    """

    def __init__(self, lang: str, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._lang = _normalize_lang(lang)

    def __call__(self, key: str, **vars: Any) -> str:
        return t_for(self._lang)(key, **vars)


def get_strings(lang: str) -> dict[str, str]:
    """Labels for a language code; anything untranslated falls back to English."""
    code = (lang or "").strip().lower()
    merged = dict(_ENGLISH)
    extra = STRINGS.get(code)
    if extra:
        merged.update(extra)
    return StringsDict(code, merged)


def lookup(key: str, lang: str) -> str:
    """Raw template for a key with English fallback, else the key itself."""
    table = STRINGS.get(_normalize_lang(lang), _ENGLISH)
    if key in table:
        return table[key]
    return _ENGLISH.get(key, key)


_PLURAL_UNIT = re.compile(r"\{(\w+)\|([\w.]+)\}")


def _has_plural(code: str, key: str) -> bool:
    """True when ``key.one``/``key.other`` variants exist (else ``count=`` stays a plain format variable, as in ``bills.item_many``)."""
    table = STRINGS.get(code, _ENGLISH)
    return (key + ".one" in table or key + ".other" in table
            or key + ".one" in _ENGLISH or key + ".other" in _ENGLISH)


def _plural_word(code: str, key: str, count: Any) -> str:
    """Unit word for ``count``: ``key.one`` when it equals 1, else ``key.other``."""
    try:
        one = int(count) == 1  # type: ignore[arg-type]
    except (TypeError, ValueError):
        one = False
    pick = key + (".one" if one else ".other")
    template = lookup(pick, code)
    if template == pick:
        template = lookup(key, code)
    return template


#: Time value home/shop contexts pass for sample shops instead of "HH:MM".
#: ``t()`` renders the sample wording below for these keys, in the UI
#: language, so frozen public templates show "Sample prices" with no edits.
SAMPLE_TIME = "sample"

#: "said today" keys -> their sample-shop wording when time == SAMPLE_TIME.
_SAMPLE_TIME_KEYS = {
    "hp.said": "hp.said_sample",
    "shop.said_short": "hp.said_sample",
    "ann.said_today": "ann.said_sample",
    "shop.notice": "shop.notice_sample",
}


def t_for(lang: str):
    """Return ``t(key, **vars)`` bound to a language with English fallback.

    Count-aware: ``t(key, count=n)`` picks ``key.one``/``key.other``, and a
    ``{var|unit.key}`` placeholder inside a template pluralizes by ``var``.
    """

    code = _normalize_lang(lang)

    def t(key: str, **vars: Any) -> str:
        if vars.get("time") == SAMPLE_TIME and key in _SAMPLE_TIME_KEYS:
            key = _SAMPLE_TIME_KEYS[key]
        if "count" in vars and _has_plural(code, key):
            count = vars.pop("count")
            vars.setdefault("n", count)
            template = _plural_word(code, key, count)
        else:
            template = lookup(key, code)
        if "default" in vars and template == key:
            default = vars.pop("default")
            template = str(default)
        if not vars:
            return template
        if "|" in template:
            template = _PLURAL_UNIT.sub(
                lambda match: _plural_word(
                    code, match.group(2), vars.get(match.group(1))),
                template)
        try:
            return template.format(**vars)
        except (KeyError, IndexError, ValueError):
            return template

    return t


def ui_lang_from_parts(cookie_val: str | None, shop_lang: str | None) -> str:
    """Seller UI language: ``ui_lang`` cookie wins, else shop ta/hi, else en."""
    cookie = (cookie_val or "").strip().lower()
    if cookie in _UI_LANGS:
        return cookie
    shop = (shop_lang or "").strip().lower()
    if shop in ("ta", "hi"):
        return shop
    return "en"


def _shop_lang_of(shop: Any) -> str:
    if shop is None:
        return "en"
    if isinstance(shop, str):
        return shop
    try:
        return str(shop["language"] or "en")
    except (KeyError, IndexError, TypeError):
        pass
    lang = getattr(shop, "language", None)
    return str(lang or "en")


def get_ui_lang(request: Any, shop: Any = None) -> str:
    """UI language for a seller request: cookie override, else shop language."""
    cookie_val = None
    try:
        cookies = getattr(request, "cookies", None)
        if isinstance(cookies, dict):
            cookie_val = cookies.get("ui_lang")
        elif cookies is not None:
            cookie_val = cookies.get("ui_lang")  # starlette Cookies
    except (AttributeError, TypeError):
        cookie_val = None
    return ui_lang_from_parts(cookie_val, _shop_lang_of(shop))


def local_date_label(lang: str, day) -> str:
    """'Thursday, 29 October' with weekday/month names in en/ta/hi.

    ``day`` is a date or datetime; digits stay ASCII in every language.
    """
    t = t_for(lang)
    return t(
        "date.full",
        weekday=t(f"date.day_{day.isoweekday()}"),
        day=f"{day.day:02d}",
        month=t(f"date.month_{day.month}"),
    )


def missing_keys() -> dict[str, list[str]]:
    """Languages mapped to sorted English keys they still lack (for tests)."""
    en_keys = set(_ENGLISH)
    return {
        lang: sorted(en_keys - set(table))
        for lang, table in STRINGS.items()
        if lang != "en"
    }


